const PAGE_TRANSLATIONS: Partial<Record<Locale, PageMap>> = { hi, bn, mr, ta, te, gu, kn };

/** Localized hero text for a tool page, falling back to the English passed in. */
export function localizePage(
  locale: Locale,
  slug: string,
  fallback: { eyebrow?: string; title: string; description: string; badges?: string[] }
) {
  const t =
    PAGE_TRANSLATIONS[locale]?.[slug] ??
    TOOL_PAGE_TRANSLATIONS[locale]?.[slug] ??
    CONTENT_PAGE_TRANSLATIONS[locale]?.[slug];
  if (!t) return fallback;
  return {
    eyebrow: t.eyebrow ?? fallback.eyebrow,
    title: t.title ?? fallback.title,
    description: t.description ?? fallback.description,
    badges: t.badges ?? fallback.badges,
  };
}
