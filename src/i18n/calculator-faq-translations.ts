const CALC_FAQS: Partial<Record<Locale, FaqMap>> = { hi, bn, mr, ta, te, gu, kn };

/** Fill {days}/{hour} style placeholders. */
function fill(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/**
 * Localised question/answer for one calculator FAQ, falling back to the
 * English source when a translation is missing.
 */
export function calcFaq(
  locale: Locale,
  slug: string,
  index: number,
  fallback: FaqPair,
  vars: Record<string, string | number> = {}
): FaqPair {
  const t = CALC_FAQS[locale]?.[`${slug}.${index}`];
  if (!t) return fallback;
  return { question: t.question, answer: fill(t.answer, vars) };
}

/** Localise a whole page's FAQ list in order. */
export function calcFaqs(
  locale: Locale,
  slug: string,
  fallbacks: FaqPair[],
  vars: Record<string, string | number> = {}
): FaqPair[] {
  return fallbacks.map((f, i) => calcFaq(locale, slug, i, f, vars));
}
